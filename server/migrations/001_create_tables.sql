CREATE TABLE IF NOT EXISTS users (
  id VARCHAR(255) NOT NULL,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL,
  phone VARCHAR(32) NULL,
  role VARCHAR(32) NOT NULL DEFAULT 'customer',
  company_name VARCHAR(255) NULL,
  gst_number VARCHAR(128) NULL,
  shipping_address LONGTEXT NULL,
  city VARCHAR(255) NULL,
  pincode VARCHAR(32) NULL,
  addresses_json LONGTEXT NULL,
  password_hash VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_users_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS orders (
  id VARCHAR(255) NOT NULL,
  order_number VARCHAR(255) NOT NULL,
  tracking_number VARCHAR(255) NULL,
  customer_name VARCHAR(255) NOT NULL,
  customer_email VARCHAR(255) NULL,
  customer_phone VARCHAR(32) NOT NULL,
  shipping_address LONGTEXT NOT NULL,
  city VARCHAR(255) NULL,
  pincode VARCHAR(32) NULL,
  subtotal DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  tax DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  shipping_fee DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  discount DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  total DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  payment_method VARCHAR(128) NOT NULL,
  payment_status VARCHAR(64) NOT NULL DEFAULT 'Pending',
  status VARCHAR(64) NOT NULL DEFAULT 'Order Placed',
  items_json LONGTEXT NOT NULL,
  timeline_json LONGTEXT NULL,
  notes LONGTEXT NULL,
  uploaded_file_url LONGTEXT NULL,
  uploaded_file_name VARCHAR(255) NULL,
  user_id VARCHAR(255) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_orders_order_number (order_number)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

